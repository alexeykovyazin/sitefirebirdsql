#!/usr/bin/env python3
"""Wrap a standalone HTML article into a Hugo page with the site header, menu and footer.

The article keeps its own CSS: rules are scoped to `.fb-article`, so they do not change
the site header and footer. html/body/* rules move to the wrapper; dark-mode rules are
dropped (the site has no dark theme).
Usage: python tools/wrap_article.py SOURCE.html URL OUT.html
Example: python tools/wrap_article.py qa.html /file/articles/firebird-qa-en.html \
             site/content/extra/firebird-qa-en.html
"""
import html
import re
import sys

SCOPE = ".fb-article"


def drop_block(css, start):
    """Remove the block that starts with `start` (with nested braces)."""
    i = css.find(start)
    if i < 0:
        return css
    j, depth = css.index("{", i), 0
    for k in range(j, len(css)):
        depth += {"{": 1, "}": -1}.get(css[k], 0)
        if depth == 0:
            return css[:i] + css[k + 1:]
    return css


def scope_css(css):
    css = drop_block(css, "@media (prefers-color-scheme: dark)")
    css = re.sub(r"(?m)^\s*(\*|html)\s*\{[^}]*\}\s*\n", "", css)
    css = re.sub(r"(?m)^(\s*)(:root|body)\s*\{", r"\1" + SCOPE + " {", css)

    def prefix(m):
        sels = [s.strip() for s in m.group(2).split(",")]
        out = [s if s.startswith(SCOPE) else SCOPE + " " + s for s in sels]
        return m.group(1) + ", ".join(out) + " {"

    return re.sub(r"(?m)^(\s*)([^@\s{}][^{};]*?)\s*\{", prefix, css)


def main():
    src, url, out = sys.argv[1:4]
    text = open(src, encoding="utf-8").read()
    title = html.unescape(re.search(r"<title>(.*?)</title>", text, re.S).group(1).strip())
    css = re.search(r"<style>(.*?)</style>", text, re.S).group(1)
    body = re.search(r"<body[^>]*>(.*)</body>", text, re.S).group(1).strip()
    q = title.replace('"', '\\"')
    fm = "\n".join([
        "---",
        'title: "Firebird: %s"' % q,
        'html_title: "Firebird: %s"' % q,
        'description: "%s"' % q,
        'og_title: "%s"' % q,
        'og_site_name: "%s"' % q,
        'source_url: ""',
        'url: "%s"' % url,
        "---",
    ])
    page = ("%s\n<!-- Generated by tools/wrap_article.py from %s. Edit the source article, then run it again. -->\n"
            "<style>%s</style>\n<section class=\"fb-article pb-80\">\n%s\n</section>\n") % (
        fm, url, scope_css(css), body)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(page)
    print("wrote %s (%d bytes)" % (out, len(page)))


if __name__ == "__main__":
    main()
