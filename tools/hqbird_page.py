#!/usr/bin/env python3
"""Make the /hqbird page from the HQbird overview (Asciidoctor HTML with embedded images).

Embedded images go to site/static/file/hqbird/2027/<alt>.png. The Asciidoctor CSS is scoped
to `.fb-article` (see wrap_article.py), and the page keeps the site breadcrumb and shop note.
The result is written to converter/manual/hqbird.html and site/content/pages/hqbird.html.
Usage: python tools/hqbird_page.py E:/Projects_2026/dochqbird/build/website/hqbird2027-overview.html
"""
import base64
import html
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wrap_article import SCOPE, scope_css  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG_DIR = "file/hqbird/2027"
OUTS = ["converter/manual/hqbird.html", "site/content/pages/hqbird.html"]

FRONT = """---
title: "Firebird: HQbird"
html_title: "%(title)s"
description: "%(desc)s"
keywords: "HQbird, Firebird, IBSurgeon, backup, monitoring, replication, HQCenter, MCP"
og_title: "%(title)s"
og_description: "%(desc)s"
og_image: "//firebirdsql.org/img/site/fb.jpg"
og_site_name: "HQbird"
menu_active: "/en/shop/"
source_url: "/hqbird"
source_format: new
url: "/hqbird"
---
<!-- Generated by tools/hqbird_page.py from %(src)s. Edit the source document, then run it again. -->
"""

BREADCRUMB = """<section class="post-layout-1-area post-layout-3-area pb-80">
    <div class="container custom-container">
        <div class="row">
            <div class="col-lg-12">
    <div class="about-author-content">
        <nav aria-label="breadcrumb">
            <ol class="breadcrumb">
                <li class="breadcrumb-item"><a href="/en/start/">Home</a></li>
                <li class="breadcrumb-item"><a href="/en/shop/">Shop</a></li>
                <li class="breadcrumb-item"><a href="/en/ibsurgeon-firebirdsql/">IBSurgeon</a></li>
                <li class="breadcrumb-item active">HQbird</li>
            </ol>
        </nav>
    </div>
</div>
            <div class="col-lg-12">
                <p style="text-align: center;"><strong>Purchases through <a href="/en/shop/">FirebirdSQL shop</a> generate commissions that fund open source Firebird development.</strong></p>
<div class="fb-article">
%s
</div>
            </div>
        </div>
    </div>
</section>
"""

# Site fonts instead of the Asciidoctor web fonts; no left TOC column.
EXTRA_CSS = """
%(s)s :is(h1,h2,h3,h4,h5,h6,p,li,td,th,dt,dd,div,span,a,strong,em,b,blockquote,#toctitle,.title){font-family:inherit}
%(s)s{font-family:"Heebo",sans-serif;color:#333;line-height:1.6}
%(s)s h1,%(s)s h2,%(s)s h3,%(s)s h4{color:#1d1d1d;font-weight:600}
%(s)s #header,%(s)s #content{max-width:none;padding-left:0;padding-right:0}
%(s)s .imageblock img{border:1px solid #dddddf}
"""


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def scope_media(css):
    """scope_css skips the first rule after `@media ...{` on the same line: prefix it too."""
    def fix(m):
        sels = [s.strip() for s in m.group(2).split(",")]
        return m.group(1) + ", ".join(SCOPE + " " + s for s in sels) + "{"
    return re.sub(r"(?m)^(@media[^{]*\{)([^@{}][^{]*)\{", fix, css)


def main():
    src = sys.argv[1]
    text = open(src, encoding="utf-8").read()
    title = html.unescape(re.search(r"<title>(.*?)</title>", text, re.S).group(1).strip())
    css = re.search(r"<style>(.*?)</style>", text, re.S).group(1)
    body = re.search(r'<div id="header">(.*)<div id="footer">', text, re.S).group(1)
    body = '<div id="header">' + body.rstrip()
    body = body.replace('<div id="toc" class="toc2">', '<div id="toc" class="toc">')
    body = body.replace("https://firebirdsql.org/", "/")
    body = re.sub(r'<div class="details">.*?</div>\n', "", body, count=1, flags=re.S)

    os.makedirs(os.path.join(ROOT, "site/static", IMG_DIR), exist_ok=True)

    def save(m):
        ext, data, alt = m.group(1), m.group(2), m.group(3)
        name = "%s.%s" % (slug(alt), "jpg" if ext == "jpeg" else ext)
        with open(os.path.join(ROOT, "site/static", IMG_DIR, name), "wb") as f:
            f.write(base64.b64decode(data))
        url = "/%s/%s" % (IMG_DIR, name)
        return '<a href="%s"><img src="%s" alt="%s" loading="lazy"></a>' % (url, url, alt)

    body, n = re.subn(r'<img src="data:image/(\w+);base64,([A-Za-z0-9+/=]+)" alt="([^"]*)">', save, body)
    if "data:image" in body:
        sys.exit("an embedded image was not converted")

    desc = re.sub(r"<[^>]+>", "", re.search(r'<div id="preamble">.*?<p>(.*?)</p>', body, re.S).group(1))
    desc = html.unescape(" ".join(desc.split())).replace('"', "'")
    page = FRONT % {"title": title.replace('"', "'"), "desc": desc, "src": os.path.basename(src)}
    page += "<style>%s%s</style>\n" % (scope_media(scope_css(css)), EXTRA_CSS % {"s": SCOPE})
    page += BREADCRUMB % body
    for out in OUTS:
        with open(os.path.join(ROOT, out), "w", encoding="utf-8", newline="\n") as f:
            f.write(page)
        print("wrote %s (%d bytes)" % (out, len(page)))
    print("images: %d in site/static/%s" % (n, IMG_DIR))


if __name__ == "__main__":
    main()
