#!/usr/bin/env python3
"""Make the /hqbird page from the HQbird 2027 content block (dochqbird project).

content.html is the block for <div class="post-layout-top-content post-layout-top-content-3">:
Bootstrap 4, Font Awesome 5 and site colours only. This script puts it into the site page with
the breadcrumb, and copies the screenshots (img/*.png) to site/static/img/shop/hqbird/2027/.
The result is written to converter/manual/hqbird.html and site/content/pages/hqbird.html.
Usage: python tools/hqbird_page.py E:/Projects_2026/dochqbird/website/firebirdsql-hqbird
"""
import glob
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG_URL = "/img/shop/hqbird/2027/"
OUTS = ["converter/manual/hqbird.html", "site/content/pages/hqbird.html"]
TITLE = "HQbird 2027: the enterprise distribution of Firebird"
DESC = ("HQbird 2027: a faster Firebird server with extra engine features, and tools for backup, "
        "monitoring, maintenance, replication and many servers in one console. "
        "100% compatible with Firebird 5.0, 4.0, 3.0 and 2.5.")

PAGE = """---
title: "Firebird: HQbird"
html_title: "%(title)s"
description: "%(desc)s"
keywords: "HQbird, Firebird, IBSurgeon, backup, monitoring, replication, HQCenter, MCP"
og_title: "%(title)s"
og_description: "%(desc)s"
og_image: "//firebirdsql.org/img/site/fb.jpg"
og_site_name: "HQbird"
menu_active: "/en/shop/"
source_url: "/hqbird"
source_format: new
url: "/hqbird"
---
<!-- Generated by tools/hqbird_page.py from dochqbird website/firebirdsql-hqbird/content.html. Edit the source, then run it again. -->
<section class="post-layout-1-area post-layout-3-area pb-80">
    <div class="container custom-container">
        <div class="row">
            <div class="col-lg-12">
    <div class="about-author-content">
        <nav aria-label="breadcrumb">
            <ol class="breadcrumb">
                <li class="breadcrumb-item"><a href="/en/start/">Home</a></li>
                <li class="breadcrumb-item"><a href="/en/shop/">Shop</a></li>
                <li class="breadcrumb-item"><a href="/en/ibsurgeon-firebirdsql/">IBSurgeon</a></li>
                <li class="breadcrumb-item active">HQbird</li>
            </ol>
        </nav>
    </div>
</div>
            <div class="col-lg-12">
                <div class="post-layout-top-content post-layout-top-content-3">
%(body)s
                </div>
            </div>
        </div>
    </div>
</section>
"""


def main():
    src = sys.argv[1]
    body = open(os.path.join(src, "content.html"), encoding="utf-8").read()
    body = re.sub(r"^\s*<!--.*?-->\s*", "", body, count=1, flags=re.S)  # note for the CMS
    body = body.replace("https://firebirdsql.org/", "/").strip()

    used = set(re.findall(re.escape(IMG_URL) + r"([\w.-]+)", body))
    dst = os.path.join(ROOT, "site/static", IMG_URL.strip("/"))
    os.makedirs(dst, exist_ok=True)
    found = set()
    for f in glob.glob(os.path.join(src, "img", "*")):
        found.add(os.path.basename(f))
        shutil.copyfile(f, os.path.join(dst, os.path.basename(f)))
    if used - found:
        sys.exit("images missing in %s/img: %s" % (src, ", ".join(sorted(used - found))))

    page = PAGE % {"title": TITLE, "desc": DESC, "body": body}
    for out in OUTS:
        with open(os.path.join(ROOT, out), "w", encoding="utf-8", newline="\n") as f:
            f.write(page)
        print("wrote %s (%d bytes)" % (out, len(page)))
    print("images: %d copied to site/static%s" % (len(found), IMG_URL))


if __name__ == "__main__":
    main()
